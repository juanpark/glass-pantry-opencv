"""Copy the phone app's item library into the web page: the baked item models and the words that match a reading
to one of them (plan v6, Juan 10/24: "not the quality we offer on the phone app").

    uv run python tools/export_items.py APP_DIR

APP_DIR is the app's Flutter folder (it holds assets/catalogue/objects.json and assets/models3d/items/). Writes
web/items/items.json and web/items/item-<key>.glb for every library row that has a baked model. The models are
our own: generated by the app's Blender script from colour blocks, with no brands, logos or bought assets.
"""

import json
import shutil
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "web" / "items"


def export(app: Path) -> list[dict]:
    rows = json.loads((app / "assets/catalogue/objects.json").read_text(encoding="utf-8"))["objects"]
    models = app / "assets/models3d/items"
    out = []
    for r in rows:
        glb = models / f"item-{r['key']}.glb"
        if not glb.exists():
            continue
        out.append({"key": r["key"], "en": r["en"], "match": [m for m in r["match"] if len(m) >= 2],
                    "mm": [r["widthMm"], r["heightMm"], r["depthMm"]]})
    OUT.mkdir(exist_ok=True)
    for old in OUT.glob("item-*.glb"):
        old.unlink()
    for r in out:
        shutil.copyfile(models / f"item-{r['key']}.glb", OUT / f"item-{r['key']}.glb")
    (OUT / "items.json").write_text(json.dumps({"items": sorted(out, key=lambda r: r["key"])}, ensure_ascii=False,
                                               indent=1) + "\n", encoding="utf-8")
    return out


if __name__ == "__main__":
    print(f"{len(export(Path(sys.argv[1])))} items exported to {OUT}")
